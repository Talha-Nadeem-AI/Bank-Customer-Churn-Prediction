"""Dataset audit and exploratory data analysis (pandas, NumPy, Matplotlib only).

Every number written into the findings is computed from the data at run time,
so the written interpretation always matches the charts.
"""
from __future__ import annotations

import logging
from pathlib import Path
from typing import Dict, List

import matplotlib

matplotlib.use("Agg")  # draw to files; works without a screen (servers, CI)
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from . import config  # noqa: E402

logger = logging.getLogger(__name__)

CHURN_COLOURS = {0: "#4C72B0", 1: "#DD8452"}
CHURN_LABELS = {0: "Stayed", 1: "Churned"}


def _save(fig: plt.Figure, name: str, out_dir: Path) -> Path:
    """Save a figure as PNG and close it to free memory."""
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / name
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return path


