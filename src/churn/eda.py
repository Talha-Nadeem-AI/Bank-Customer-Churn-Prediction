def audit_dataset(raw: pd.DataFrame) -> Dict[str, object]:
    """Compute the data-quality facts required by the dataset audit."""
    target_counts = raw[config.TARGET].value_counts().sort_index()
    return {
        "rows": int(raw.shape[0]),
        "columns": int(raw.shape[1]),
        "missing_values_total": int(raw.isna().sum().sum()),
        "missing_by_column": raw.isna().sum().to_dict(),
        "duplicate_rows": int(raw.duplicated().sum()),
        "duplicate_customer_ids": int(raw["CustomerId"].duplicated().sum()) if "CustomerId" in raw else None,
        "stayed": int(target_counts.get(0, 0)),
        "churned": int(target_counts.get(1, 0)),
        "churn_rate": float(raw[config.TARGET].mean()),
        "zero_balance_share": float((raw["Balance"] == 0).mean()),
        "personal_data_columns": [c for c in ("Surname", "CustomerId") if c in raw.columns],
    }


def data_dictionary(raw: pd.DataFrame) -> pd.DataFrame:
    """Build a data dictionary table: name, type, description, example range."""
    rows = []
    for col in raw.columns:
        series = raw[col]
        if pd.api.types.is_numeric_dtype(series):
            values = f"{series.min():g} to {series.max():g}"
        else:
            uniques = series.dropna().unique()
            values = ", ".join(map(str, uniques[:5])) + (" ..." if len(uniques) > 5 else "")
            values = f"{len(uniques)} unique: {values}"
        rows.append({
            "column": col,
            "dtype": str(series.dtype),
            "role": "target" if col == config.TARGET else ("identifier (dropped)" if col in config.ID_COLUMNS else "feature"),
            "description": config.DATA_DICTIONARY.get(col, ""),
            "values": values,
            "missing": int(series.isna().sum()),
        })
    return pd.DataFrame(rows)


def write_audit_report(raw: pd.DataFrame, cleaning_report: Dict[str, int], path: Path) -> Dict[str, object]:
    """Write the dataset audit and data dictionary to a Markdown file."""
    audit = audit_dataset(raw)
    dictionary = data_dictionary(raw)
    lines = [
        "# Dataset Audit (generated by the pipeline)",
        "",
        "## Overview",
        f"- Rows: **{audit['rows']:,}**, columns: **{audit['columns']}**",
        f"- Missing values: **{audit['missing_values_total']}**",
        f"- Duplicate rows: **{audit['duplicate_rows']}**; duplicate CustomerIds: **{audit['duplicate_customer_ids']}**",
        f"- Class balance: stayed **{audit['stayed']:,}**, churned **{audit['churned']:,}** "
        f"(churn rate **{audit['churn_rate']:.1%}**) -> imbalanced",
        f"- Customers with zero balance: **{audit['zero_balance_share']:.1%}** (a real value, not missing data)",
        f"- Personal data columns: {', '.join(audit['personal_data_columns'])} -> removed during cleaning",
        "",
        "## Cleaning steps applied",
    ]
    lines += [f"- {k}: {v}" for k, v in cleaning_report.items()]
    lines += ["", "## Data dictionary", "", _markdown_table(dictionary)]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return audit


def _markdown_table(df: pd.DataFrame) -> str:
    """Render a DataFrame as a Markdown table without extra dependencies."""
    header = "| " + " | ".join(df.columns) + " |"
    sep = "| " + " | ".join("---" for _ in df.columns) + " |"
    body = ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([header, sep] + body)


