def plot_class_balance(df: pd.DataFrame, out_dir: Path) -> str:
    """Figure 1: how many customers stayed vs churned."""
    counts = df[config.TARGET].value_counts().sort_index()
    fig, ax = plt.subplots(figsize=(6, 4))
    bars = ax.bar([CHURN_LABELS[i] for i in counts.index], counts.values,
                  color=[CHURN_COLOURS[i] for i in counts.index])
    for bar, value in zip(bars, counts.values):
        ax.text(bar.get_x() + bar.get_width() / 2, value, f"{value:,}\n({value / counts.sum():.1%})",
                ha="center", va="bottom")
    ax.set_title("Figure 1. Class balance of the target (Exited)")
    ax.set_ylabel("Number of customers")
    ax.set_ylim(0, counts.max() * 1.18)
    _save(fig, "eda_01_class_balance.png", out_dir)
    rate = counts.get(1, 0) / counts.sum()
    return (f"Only {rate:.1%} of customers churned, so the classes are imbalanced. A model that always "
            f"predicts 'stays' would already be {1 - rate:.1%} accurate, which is why accuracy alone is "
            f"misleading and recall/F1 are used to judge models.")


def plot_age_distribution(df: pd.DataFrame, out_dir: Path) -> str:
    """Figure 2: age distribution for churned vs retained customers."""
    fig, ax = plt.subplots(figsize=(7, 4))
    bins = np.arange(18, 96, 3)
    for label in (0, 1):
        ax.hist(df.loc[df[config.TARGET] == label, "Age"], bins=bins, alpha=0.6,
                color=CHURN_COLOURS[label], label=CHURN_LABELS[label], density=True)
    ax.set_title("Figure 2. Age distribution by churn status")
    ax.set_xlabel("Age (years)")
    ax.set_ylabel("Density")
    ax.legend()
    _save(fig, "eda_02_age_by_churn.png", out_dir)
    med_churn = df.loc[df[config.TARGET] == 1, "Age"].median()
    med_stay = df.loc[df[config.TARGET] == 0, "Age"].median()
    band = df[df["Age"].between(50, 59)][config.TARGET].mean()
    young = df[df["Age"] < 30][config.TARGET].mean()
    return (f"Churned customers are older (median age {med_churn:.0f} vs {med_stay:.0f}). Churn peaks at "
            f"{band:.1%} for ages 50-59 compared with {young:.1%} for under-30s, so Age is one of the "
            f"strongest predictors.")


def plot_churn_by_products(df: pd.DataFrame, out_dir: Path) -> str:
    """Figure 3: churn rate by number of products held."""
    grp = df.groupby("NumOfProducts")[config.TARGET].agg(["mean", "count"])
    fig, ax = plt.subplots(figsize=(6, 4))
    bars = ax.bar(range(len(grp)), grp["mean"] * 100, color="#55A868", tick_label=[str(i) for i in grp.index])
    for bar, (rate, n) in zip(bars, grp.itertuples(index=False)):
        ax.text(bar.get_x() + bar.get_width() / 2, rate * 100, f"{rate:.0%}\n(n={n:,})", ha="center", va="bottom")
    ax.set_title("Figure 3. Churn rate by number of products")
    ax.set_xlabel("Number of bank products")
    ax.set_ylabel("Churn rate (%)")
    ax.set_ylim(0, 115)
    _save(fig, "eda_03_churn_by_products.png", out_dir)
    r = grp["mean"]
    return (f"The relationship is not linear: customers with 2 products churn least ({r.get(2, np.nan):.1%}), "
            f"1 product is {r.get(1, np.nan):.1%}, while 3 products ({r.get(3, np.nan):.1%}) and 4 products "
            f"({r.get(4, np.nan):.1%}, only {int(grp['count'].get(4, 0))} customers) almost always churn. "
            f"Tree-based models can capture this non-linear pattern better than logistic regression.")


def plot_churn_by_geography_gender(df: pd.DataFrame, out_dir: Path) -> str:
    """Figure 4: churn rate by country, split by gender."""
    table = df.pivot_table(index="Geography", columns="Gender", values=config.TARGET, aggfunc="mean") * 100
    fig, ax = plt.subplots(figsize=(7, 4))
    x = np.arange(len(table.index))
    width = 0.38
    for i, gender in enumerate(table.columns):
        ax.bar(x + (i - 0.5) * width, table[gender], width, label=gender)
    ax.set_xticks(x)
    ax.set_xticklabels(table.index)
    ax.set_title("Figure 4. Churn rate by country and gender")
    ax.set_ylabel("Churn rate (%)")
    ax.legend(title="Gender")
    _save(fig, "eda_04_churn_by_geography_gender.png", out_dir)
    geo = df.groupby("Geography")[config.TARGET].mean()
    gen = df.groupby("Gender")[config.TARGET].mean()
    return (f"Germany has the highest churn ({geo.get('Germany', np.nan):.1%}) versus France "
            f"({geo.get('France', np.nan):.1%}) and Spain ({geo.get('Spain', np.nan):.1%}). Female customers churn "
            f"more ({gen.get('Female', np.nan):.1%}) than male customers ({gen.get('Male', np.nan):.1%}) in every "
            f"country. These are sensitive attributes, so the model's errors are checked per group in the "
            f"fairness analysis.")


def plot_activity_and_balance(df: pd.DataFrame, out_dir: Path) -> str:
    """Figure 5: churn by activity status, and the zero-balance effect."""
    fig, axes = plt.subplots(1, 2, figsize=(10, 4))
    act = df.groupby("IsActiveMember")[config.TARGET].mean() * 100
    axes[0].bar(["Inactive", "Active"], act.values, color=["#C44E52", "#4C72B0"])
    axes[0].set_title("Churn rate by activity")
    axes[0].set_ylabel("Churn rate (%)")
    zero = df.assign(ZeroBalance=np.where(df["Balance"] == 0, "Zero balance", "Has balance"))
    zrate = zero.groupby("ZeroBalance")[config.TARGET].mean() * 100
    axes[1].bar(zrate.index, zrate.values, color=["#8172B2", "#937860"])
    axes[1].set_title("Churn rate by balance status")
    axes[1].set_ylabel("Churn rate (%)")
    fig.suptitle("Figure 5. Engagement and balance vs churn")
    _save(fig, "eda_05_activity_balance.png", out_dir)
    return (f"Inactive members churn at {act.iloc[0]:.1f}% compared with {act.iloc[1]:.1f}% for active members. "
            f"Customers holding a balance churn at {zrate.get('Has balance', np.nan):.1f}% vs "
            f"{zrate.get('Zero balance', np.nan):.1f}% for zero-balance customers, which motivates the "
            f"engineered HasZeroBalance feature.")


def plot_correlation_matrix(df: pd.DataFrame, out_dir: Path) -> str:
    """Figure 6: correlation between numeric features and the target."""
    numeric = df[config.NUMERIC_FEATURES + [config.TARGET]]
    corr = numeric.corr().to_numpy()
    labels = list(numeric.columns)
    fig, ax = plt.subplots(figsize=(8, 7))
    im = ax.imshow(corr, cmap="coolwarm", vmin=-1, vmax=1)
    ax.set_xticks(range(len(labels)))
    ax.set_xticklabels(labels, rotation=45, ha="right")
    ax.set_yticks(range(len(labels)))
    ax.set_yticklabels(labels)
    for i in range(len(labels)):
        for j in range(len(labels)):
            ax.text(j, i, f"{corr[i, j]:.2f}", ha="center", va="center", fontsize=7)
    fig.colorbar(im, ax=ax, fraction=0.046)
    ax.set_title("Figure 6. Correlation matrix (numeric features)")
    _save(fig, "eda_06_correlation_matrix.png", out_dir)
    target_corr = numeric.corr()[config.TARGET].drop(config.TARGET).sort_values(key=np.abs, ascending=False)
    top = ", ".join(f"{k} ({v:+.2f})" for k, v in target_corr.head(3).items())
    weak = ", ".join(f"{k} ({v:+.2f})" for k, v in target_corr.tail(3).items())
    max_pair = np.abs(corr - np.eye(len(labels)))[:-1, :-1].max()
    return (f"Strongest linear links with churn: {top}. Weakest: {weak}. No two input features are strongly "
            f"correlated (largest |r| = {max_pair:.2f}), so multicollinearity is not a concern. Weak linear "
            f"correlation does not rule out non-linear effects (e.g. NumOfProducts).")


def plot_numeric_boxplots(df: pd.DataFrame, out_dir: Path) -> str:
    """Figure 7: distribution of key numeric features by churn status."""
    cols = ["CreditScore", "Balance", "EstimatedSalary", "Tenure"]
    fig, axes = plt.subplots(1, len(cols), figsize=(14, 4))
    for ax, col in zip(axes, cols):
        data = [df.loc[df[config.TARGET] == k, col] for k in (0, 1)]
        ax.boxplot(data)
        ax.set_xticks([1, 2])
        ax.set_xticklabels(["Stayed", "Churned"])
        ax.set_title(col)
    fig.suptitle("Figure 7. Numeric features by churn status")
    _save(fig, "eda_07_numeric_boxplots.png", out_dir)
    diffs = {c: df.groupby(config.TARGET)[c].median() for c in cols}
    text = "; ".join(f"{c}: median {d.get(0, np.nan):,.0f} (stayed) vs {d.get(1, np.nan):,.0f} (churned)"
                     for c, d in diffs.items())
    return (f"{text}. CreditScore, EstimatedSalary and Tenure barely differ between the groups, which supports "
            f"testing a model without the weakest features in the feature-selection experiment.")


def run_eda(df: pd.DataFrame, out_dir: Path = config.FIGURES_DIR) -> List[Dict[str, str]]:
    """Create every EDA figure and return its file name with an interpretation."""
    plots = [
        ("eda_01_class_balance.png", plot_class_balance),
        ("eda_02_age_by_churn.png", plot_age_distribution),
        ("eda_03_churn_by_products.png", plot_churn_by_products),
        ("eda_04_churn_by_geography_gender.png", plot_churn_by_geography_gender),
        ("eda_05_activity_balance.png", plot_activity_and_balance),
        ("eda_06_correlation_matrix.png", plot_correlation_matrix),
        ("eda_07_numeric_boxplots.png", plot_numeric_boxplots),
    ]
    findings = []
    for name, func in plots:
        findings.append({"figure": name, "finding": func(df, out_dir)})
        logger.info("Saved %s", name)
    return findings


def write_eda_findings(findings: List[Dict[str, str]], path: Path) -> None:
    """Save the EDA interpretations as Markdown for the report."""
    lines = ["# EDA Findings (generated by the pipeline)", ""]
    for i, item in enumerate(findings, start=1):
        lines += [f"## {i}. `{item['figure']}`", "", item["finding"], ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
